    bool CreateTextureImageFromFile( VkPhysicalDevice   physical_device,
                                     VmaAllocator       allocator,
                                     VkDevice           logical_device,
                                     VkCommandPool      command_pool,
                                     VkQueue            queue,
                                     char const       * filename,
                                     AllocatedImage   & image ) {
        // STBI_rgb_alpha adds an alpha channel if the file has none, so every texel is 4 bytes
        int width = 0;
        int height = 0;
        int channels = 0;
        std::unique_ptr<stbi_uc, void( * )( void * )> pixels( stbi_load( filename, &width, &height, &channels, STBI_rgb_alpha ), stbi_image_free );
        if( !pixels ) {
            std::cout << "Could not load texture image '" << filename << "': " << stbi_failure_reason() << std::endl;
            return false;
        }
        VkDeviceSize image_size = static_cast<VkDeviceSize>(width) * static_cast<VkDeviceSize>(height) * 4;

        // Staging buffer in CPU visible memory - destroyed when this function returns
        AllocatedBuffer staging_buffer;
        if( !CreateBuffer( allocator, image_size, VK_BUFFER_USAGE_TRANSFER_SRC_BIT, MemoryLocation::HostVisibleMapped, staging_buffer ) ||
            !CopyDataToBuffer( staging_buffer, 0, image_size, pixels.get() ) ) {
            return false;
        }
        pixels.reset();

        // Full mip chain if the device can generate it for this format, otherwise only the original image
        uint32_t mip_levels = CalculateMipLevelCount( static_cast<uint32_t>(width), static_cast<uint32_t>(height) );
        if( !IsMipmapGenerationSupported( physical_device, VK_FORMAT_R8G8B8A8_SRGB ) ) {
            std::cout << "Texture format does not support linear blitting - '" << filename << "' is loaded without mipmaps." << std::endl;
            mip_levels = 1;
        }
        std::cout << "Loaded texture : " << width << "x" << height << ", " << mip_levels << " mip levels" << std::endl;

        // Optimal tiling - texels are stored in an implementation defined order that is fastest for sampling.
        // Transfer source usage is needed because every mip level is generated by reading the previous one.
        if( !CreateImage( allocator, static_cast<uint32_t>(width), static_cast<uint32_t>(height), mip_levels, VK_SAMPLE_COUNT_1_BIT,
                          VK_FORMAT_R8G8B8A8_SRGB, VK_IMAGE_TILING_OPTIMAL,
                          VK_IMAGE_USAGE_TRANSFER_SRC_BIT | VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_SAMPLED_BIT, image ) ) {
            return false;
        }

        // Transition of all levels, copy to level 0 and mipmap generation (which also transitions every level to the
        // shader read layout) are recorded into one command buffer and submitted once
        VkCommandBuffer command_buffer;
        if( !BeginSingleTimeCommands( logical_device, command_pool, command_buffer ) ) {
            return false;
        }
        bool recorded = RecordImageLayoutTransition( command_buffer, *image, VK_FORMAT_R8G8B8A8_SRGB, VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL );
        if( recorded ) {
            RecordCopyBufferToImage( command_buffer, *staging_buffer, *image, static_cast<uint32_t>(width), static_cast<uint32_t>(height) );
            RecordMipmapGeneration( command_buffer, *image, static_cast<uint32_t>(width), static_cast<uint32_t>(height), mip_levels );
        }
        // Always ended, so the command buffer is freed even if recording failed
        bool submitted = EndSingleTimeCommands( logical_device, command_pool, queue, command_buffer );
        return recorded && submitted;
    }

    bool CreateTextureFromFile( VkPhysicalDevice   physical_device,
                                VmaAllocator       allocator,
                                VkDevice           logical_device,
                                VkCommandPool      command_pool,
                                VkQueue            queue,
                                char const       * filename,
                                float              max_anisotropy,
                                Texture          & texture ) {
        if( !CreateTextureImageFromFile( physical_device, allocator, logical_device, command_pool, queue, filename, texture.Image ) ) {
            return false;
        }

        InitVkDestroyer( logical_device, texture.ImageView );
        if( !CreateImageView( logical_device, *texture.Image, VK_IMAGE_VIEW_TYPE_2D, VK_FORMAT_R8G8B8A8_SRGB, VK_IMAGE_ASPECT_COLOR_BIT, *texture.ImageView ) ) {
            return false;
        }

        InitVkDestroyer( logical_device, texture.Sampler );
        return CreateSampler( logical_device, VK_FILTER_LINEAR, VK_SAMPLER_ADDRESS_MODE_REPEAT, true, max_anisotropy, *texture.Sampler );
    }

